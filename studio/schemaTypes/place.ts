import { defineArrayMember, defineField, defineType } from 'sanity';

/** A village, monument or site: one fitxa in the app. */
export const place = defineType({
  name: 'place',
  title: 'Lloc',
  type: 'document',
  groups: [
    { name: 'basic', title: 'Dades', default: true },
    { name: 'text', title: 'Text' },
    { name: 'map', title: 'Mapa i punts destacats' },
    { name: 'photos', title: 'Fotos' },
  ],
  fields: [
    defineField({
      name: 'name',
      title: 'Nom',
      type: 'string',
      group: 'basic',
      validation: (rule) => rule.required(),
    }),
    defineField({
      name: 'slug',
      title: 'Adreça',
      type: 'slug',
      group: 'basic',
      description: 'Surt a l\'enllaç de la fitxa (/lloc/rupit). Prem "Generate" i no la canviïs després.',
      options: { source: 'name', maxLength: 60 },
      validation: (rule) => rule.required(),
    }),
    defineField({ name: 'comarca', title: 'Comarca', type: 'string', group: 'basic', validation: (rule) => rule.required() }),
    defineField({ name: 'regio', title: 'Regió', type: 'string', group: 'basic', description: 'Ex.: Catalunya Central', validation: (rule) => rule.required() }),
    defineField({ name: 'habitants', title: 'Habitants', type: 'number', group: 'basic', validation: (rule) => rule.min(0).integer() }),
    defineField({ name: 'altitud', title: 'Altitud (m)', type: 'number', group: 'basic' }),
    defineField({
      name: 'categories',
      title: 'Categories',
      type: 'array',
      group: 'basic',
      description: 'Serveixen per als filtres "Patrimoni" i "Natura".',
      of: [defineArrayMember({ type: 'string' })],
      options: {
        list: [
          { title: 'Patrimoni', value: 'patrimoni' },
          { title: 'Natura', value: 'natura' },
        ],
      },
    }),
    defineField({
      name: 'routeTag',
      title: 'Etiqueta de ruta',
      type: 'string',
      group: 'basic',
      description: 'La paraula en lletra gòtica sobre el nom. Ex.: Collsacabra.',
    }),
    defineField({
      name: 'teaser',
      title: 'Frase curta',
      type: 'string',
      group: 'text',
      description: 'Per a les llistes de Descobreix. Una sola línia.',
      validation: (rule) => rule.max(80),
    }),
    defineField({ name: 'introText', title: 'Introducció', type: 'text', rows: 5, group: 'text' }),
    defineField({ name: 'contextText', title: 'El relat', type: 'text', rows: 6, group: 'text' }),
    defineField({
      name: 'lat',
      title: 'Latitud',
      type: 'number',
      group: 'map',
      description: 'El centre del poble. Es pot copiar amb clic dret a Google Maps o OpenStreetMap.',
      validation: (rule) => rule.required().min(40).max(43),
    }),
    defineField({
      name: 'lng',
      title: 'Longitud',
      type: 'number',
      group: 'map',
      validation: (rule) => rule.required().min(0).max(4),
    }),
    defineField({
      name: 'highlights',
      title: 'Punts destacats',
      type: 'array',
      group: 'map',
      description: 'Surten a la fitxa i, si tenen ubicació, dibuixats al mapa en acostar-s\'hi.',
      of: [defineArrayMember({ type: 'highlight' })],
    }),
    defineField({
      name: 'nearby',
      title: 'Llocs a prop',
      type: 'array',
      group: 'map',
      description: 'Les distàncies es calculen soles a partir de les ubicacions.',
      of: [defineArrayMember({ type: 'reference', to: [{ type: 'place' }] })],
    }),
    defineField({
      name: 'photo',
      title: 'Foto de capçalera',
      type: 'image',
      group: 'photos',
      options: { hotspot: true },
    }),
    defineField({
      name: 'gallery',
      title: 'Galeria',
      type: 'array',
      group: 'photos',
      of: [defineArrayMember({ type: 'image', options: { hotspot: true } })],
    }),
  ],
  preview: {
    select: { title: 'name', subtitle: 'comarca', media: 'photo' },
  },
});
